-- 001_core_schema.sql — single source of truth
CREATE TABLE IF NOT EXISTS users (
  id CHAR(36) PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('CLIENT','OWNER') NOT NULL,
  company VARCHAR(160) NULL,
  phone VARCHAR(32) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS locations (
  id CHAR(36) PRIMARY KEY,
  owner_id CHAR(36) NOT NULL,
  name VARCHAR(160) NOT NULL,
  address_line VARCHAR(255) NOT NULL,
  city VARCHAR(100) NOT NULL,
  state VARCHAR(100) NULL,
  country VARCHAR(100) NOT NULL DEFAULT 'India',
  timezone VARCHAR(64) NOT NULL DEFAULT 'Asia/Kolkata',
  latitude DECIMAL(9,6) NULL, longitude DECIMAL(9,6) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  CONSTRAINT fk_loc_owner FOREIGN KEY (owner_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS rooms (
  id CHAR(36) PRIMARY KEY,
  owner_id CHAR(36) NOT NULL,
  location_id CHAR(36) NOT NULL,
  name VARCHAR(160) NOT NULL,
  description TEXT NULL,
  floor VARCHAR(32) NULL,
  capacity INT UNSIGNED NOT NULL,
  room_type ENUM('MEETING','BOARDROOM','HUDDLE','TRAINING','PHONE_BOOTH','COWORKING') NOT NULL DEFAULT 'MEETING',
  vibe ENUM('FORMAL','CASUAL','CREATIVE','QUIET','PRESENTATION') NOT NULL DEFAULT 'FORMAL',
  hourly_price DECIMAL(10,2) NOT NULL DEFAULT 0,
  currency CHAR(3) NOT NULL DEFAULT 'INR',
  photos JSON NOT NULL DEFAULT (JSON_ARRAY()),
  status ENUM('ACTIVE','INACTIVE','MAINTENANCE') NOT NULL DEFAULT 'ACTIVE',
  open_time TIME NOT NULL DEFAULT '09:00:00',
  close_time TIME NOT NULL DEFAULT '19:00:00',
  open_days JSON NOT NULL DEFAULT (JSON_ARRAY(1,2,3,4,5)),
  min_booking_minutes INT UNSIGNED NOT NULL DEFAULT 30,
  max_booking_minutes INT UNSIGNED NOT NULL DEFAULT 480,
  buffer_minutes INT UNSIGNED NOT NULL DEFAULT 0,
  checkin_grace_minutes TINYINT UNSIGNED NOT NULL DEFAULT 15,
  qr_token CHAR(36) NOT NULL UNIQUE,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) NULL,
  KEY idx_rooms_loc (location_id), KEY idx_rooms_owner (owner_id), KEY idx_rooms_search (status, capacity),
  CONSTRAINT fk_room_owner FOREIGN KEY (owner_id) REFERENCES users(id),
  CONSTRAINT fk_room_loc FOREIGN KEY (location_id) REFERENCES locations(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS equipment_types (
  id CHAR(36) PRIMARY KEY,
  code VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(80) NOT NULL,
  icon VARCHAR(40) NOT NULL,
  category ENUM('DISPLAY','AUDIO_VIDEO','COLLABORATION','CONNECTIVITY','COMFORT','ACCESSIBILITY') NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS room_equipment (
  id CHAR(36) PRIMARY KEY,
  room_id CHAR(36) NOT NULL,
  equipment_type_id CHAR(36) NOT NULL,
  quantity INT UNSIGNED NOT NULL DEFAULT 1,
  status ENUM('WORKING','FAULTY','MAINTENANCE') NOT NULL DEFAULT 'WORKING',
  notes VARCHAR(255) NULL,
  flagged_at DATETIME(3) NULL,
  flagged_reason VARCHAR(255) NULL,
  UNIQUE KEY uq_room_equipment (room_id, equipment_type_id),
  CONSTRAINT fk_re_room FOREIGN KEY (room_id) REFERENCES rooms(id) ON DELETE CASCADE,
  CONSTRAINT fk_re_type FOREIGN KEY (equipment_type_id) REFERENCES equipment_types(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS room_blackouts (
  id CHAR(36) PRIMARY KEY,
  room_id CHAR(36) NOT NULL,
  start_at DATETIME(3) NOT NULL, end_at DATETIME(3) NOT NULL,
  reason VARCHAR(255) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  KEY idx_bo_room_time (room_id, start_at, end_at),
  CONSTRAINT fk_bo_room FOREIGN KEY (room_id) REFERENCES rooms(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS bookings (
  id CHAR(36) PRIMARY KEY,
  room_id CHAR(36) NOT NULL,
  client_id CHAR(36) NOT NULL,
  title VARCHAR(160) NOT NULL,
  notes VARCHAR(500) NULL,
  start_at DATETIME(3) NOT NULL,
  end_at DATETIME(3) NOT NULL,
  attendee_count INT UNSIGNED NOT NULL,
  required_equipment JSON NOT NULL DEFAULT (JSON_ARRAY()),
  status ENUM('HELD','CONFIRMED','CHECKED_IN','COMPLETED','CANCELLED','NO_SHOW','RELEASED') NOT NULL,
  hold_expires_at DATETIME(3) NULL,
  checked_in_at DATETIME(3) NULL,
  cancelled_at DATETIME(3) NULL,
  cancel_reason VARCHAR(255) NULL,
  source ENUM('WEB','ROOMBOT') NOT NULL DEFAULT 'WEB',
  total_price DECIMAL(10,2) NOT NULL DEFAULT 0,
  match_score TINYINT UNSIGNED NULL,
  match_reason VARCHAR(500) NULL,
  idempotency_key VARCHAR(64) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  KEY idx_b_room_time (room_id, start_at, end_at, status),
  KEY idx_b_client (client_id, start_at),
  KEY idx_b_status_time (status, start_at),
  UNIQUE KEY uq_b_idem (client_id, idempotency_key),
  CONSTRAINT fk_b_room FOREIGN KEY (room_id) REFERENCES rooms(id),
  CONSTRAINT fk_b_client FOREIGN KEY (client_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS booking_participants (
  id CHAR(36) PRIMARY KEY,
  booking_id CHAR(36) NOT NULL,
  user_id CHAR(36) NULL,
  email VARCHAR(190) NOT NULL,
  name VARCHAR(120) NULL,
  status ENUM('INVITED','ACCEPTED','DECLINED') NOT NULL DEFAULT 'INVITED',
  KEY idx_bp_user (user_id), KEY idx_bp_booking (booking_id),
  CONSTRAINT fk_bp_booking FOREIGN KEY (booking_id) REFERENCES bookings(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS reviews (
  id CHAR(36) PRIMARY KEY,
  booking_id CHAR(36) NOT NULL UNIQUE,
  room_id CHAR(36) NOT NULL,
  reviewer_id CHAR(36) NOT NULL,
  rating TINYINT UNSIGNED NOT NULL,
  comment VARCHAR(500) NULL,
  tags JSON NOT NULL DEFAULT (JSON_ARRAY()),
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  KEY idx_r_room (room_id, created_at),
  CONSTRAINT chk_rating CHECK (rating BETWEEN 1 AND 10),
  CONSTRAINT fk_r_booking FOREIGN KEY (booking_id) REFERENCES bookings(id),
  CONSTRAINT fk_r_room FOREIGN KEY (room_id) REFERENCES rooms(id),
  CONSTRAINT fk_r_user FOREIGN KEY (reviewer_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS room_issues (
  id CHAR(36) PRIMARY KEY,
  room_id CHAR(36) NOT NULL,
  booking_id CHAR(36) NULL,
  reporter_id CHAR(36) NOT NULL,
  equipment_type_id CHAR(36) NULL,
  issue_type ENUM('EQUIPMENT_BROKEN','TOO_SMALL','TOO_NOISY','CLEANLINESS','OTHER') NOT NULL,
  description VARCHAR(500) NULL,
  status ENUM('OPEN','ACKNOWLEDGED','RESOLVED') NOT NULL DEFAULT 'OPEN',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  resolved_at DATETIME(3) NULL,
  KEY idx_i_room_status (room_id, status),
  CONSTRAINT fk_i_room FOREIGN KEY (room_id) REFERENCES rooms(id),
  CONSTRAINT fk_i_user FOREIGN KEY (reporter_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS room_stats (
  room_id CHAR(36) PRIMARY KEY,
  avg_rating DECIMAL(4,2) NULL,
  bayes_rating DECIMAL(4,2) NULL,
  review_count INT UNSIGNED NOT NULL DEFAULT 0,
  booking_count INT UNSIGNED NOT NULL DEFAULT 0,
  no_show_count INT UNSIGNED NOT NULL DEFAULT 0,
  open_issue_count INT UNSIGNED NOT NULL DEFAULT 0,
  utilization_pct DECIMAL(5,2) NOT NULL DEFAULT 0,
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  CONSTRAINT fk_rs_room FOREIGN KEY (room_id) REFERENCES rooms(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS slot_demand_stats (
  location_id CHAR(36) NOT NULL,
  day_of_week TINYINT UNSIGNED NOT NULL,
  hour_of_day TINYINT UNSIGNED NOT NULL,
  fill_rate DECIMAL(5,2) NOT NULL,
  sample_size INT UNSIGNED NOT NULL,
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (location_id, day_of_week, hour_of_day),
  CONSTRAINT fk_sds_loc FOREIGN KEY (location_id) REFERENCES locations(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS chat_sessions (
  id CHAR(36) PRIMARY KEY,
  user_id CHAR(36) NOT NULL,
  state JSON NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  CONSTRAINT fk_cs_user FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS chat_messages (
  id CHAR(36) PRIMARY KEY,
  session_id CHAR(36) NOT NULL,
  role ENUM('USER','ASSISTANT','SYSTEM') NOT NULL,
  content TEXT NOT NULL,
  metadata JSON NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  KEY idx_cm_session (session_id, created_at),
  CONSTRAINT fk_cm_session FOREIGN KEY (session_id) REFERENCES chat_sessions(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS notifications (
  id CHAR(36) PRIMARY KEY,
  user_id CHAR(36) NOT NULL,
  type ENUM('BOOKING_CONFIRMED','BOOKING_CANCELLED','BOOKING_RELEASED','BOOKING_REMINDER','REVIEW_REQUESTED','ISSUE_REPORTED','ISSUE_RESOLVED','EQUIPMENT_FLAGGED','SYSTEM') NOT NULL,
  title VARCHAR(160) NOT NULL,
  body VARCHAR(500) NOT NULL,
  data JSON NULL,
  read_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  KEY idx_n_user (user_id, read_at, created_at),
  CONSTRAINT fk_n_user FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

