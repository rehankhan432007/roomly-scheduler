#!/usr/bin/env node
// gen-registry.mjs — Scans modules/*/index.ts and features/*/manifest.ts, generates registry files
import { readdirSync, existsSync, writeFileSync } from 'fs';
import { join, resolve } from 'path';
import { fileURLToPath } from 'url';

const __dirname = fileURLToPath(new URL('.', import.meta.url));
const root = resolve(__dirname, '..');

// ---- API modules ----
const apiModulesDir = join(root, 'apps', 'api', 'src', 'modules');
const apiOutputFile = join(root, 'apps', 'api', 'src', 'core', 'modules.generated.ts');

let apiImports = '';
let apiExports = '// Generated module registry — DO NOT EDIT\n';
apiExports += '// This file is auto-generated by scripts/gen-registry.mjs\n';
apiExports += "import type { ApiModule } from '@meetmaze/shared/contracts';\n\n";

const moduleNames = [];

if (existsSync(apiModulesDir)) {
  const dirs = readdirSync(apiModulesDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();

  for (const dir of dirs) {
    const indexFile = join(apiModulesDir, dir, 'index.ts');
    if (existsSync(indexFile)) {
      const varName = `mod_${dir.replace(/-/g, '_')}`;
      apiImports += `import ${varName} from '../modules/${dir}/index.js';\n`;
      moduleNames.push(varName);
    }
  }
}

apiExports += apiImports + '\n';
apiExports += `export const modules: ApiModule[] = [${moduleNames.join(', ')}];\n`;

writeFileSync(apiOutputFile, apiExports, 'utf-8');
console.log(`✅ Generated ${apiOutputFile} (${moduleNames.length} modules)`);

// ---- Web features ----
const webFeaturesDir = join(root, 'apps', 'web', 'src', 'features');
const webOutputFile = join(root, 'apps', 'web', 'src', 'core', 'features.generated.ts');

let webImports = '';
let webExportsContent = '// Generated feature registry — DO NOT EDIT\n';
webExportsContent += '// This file is auto-generated by scripts/gen-registry.mjs\n';
webExportsContent += "import type { FeatureManifest } from '@meetmaze/shared/contracts';\n\n";

const featureNames = [];

if (existsSync(webFeaturesDir)) {
  const dirs = readdirSync(webFeaturesDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();

  for (const dir of dirs) {
    const manifestFile = join(webFeaturesDir, dir, 'manifest.ts');
    if (existsSync(manifestFile)) {
      const varName = `feat_${dir.replace(/-/g, '_')}`;
      webImports += `import { manifest as ${varName} } from '../features/${dir}/manifest';\n`;
      featureNames.push(varName);
    }
  }
}

webExportsContent += webImports + '\n';
webExportsContent += `export const features: FeatureManifest[] = [${featureNames.join(', ')}];\n`;

writeFileSync(webOutputFile, webExportsContent, 'utf-8');
console.log(`✅ Generated ${webOutputFile} (${featureNames.length} features)`);
