#!/usr/bin/env node
/**
 * gen-registry.mjs
 * Scans apps/api/src/modules/[module]/index.ts and writes apps/api/src/core/modules.generated.ts
 * Scans apps/web/src/features/[feature]/manifest.ts and writes apps/web/src/core/features.generated.ts
 */
import { readdir, writeFile, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

async function exists(p) {
  try { await access(p); return true; } catch { return false; }
}

async function genApiModules() {
  const modulesDir = path.join(root, 'apps/api/src/modules');
  let names = [];
  try {
    const entries = await readdir(modulesDir, { withFileTypes: true });
    for (const e of entries) {
      if (!e.isDirectory()) continue;
      const idx = path.join(modulesDir, e.name, 'index.ts');
      if (await exists(idx)) names.push(e.name);
    }
  } catch {}
  names.sort();

  const imports = names.map((n, i) => `import mod${i} from '../modules/${n}/index.js';`).join('\n');
  const exports = `export default [${names.map((_, i) => `mod${i}`).join(', ')}];`;
  const content = `// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit\n${imports}\n${exports}\n`;
  const outPath = path.join(root, 'apps/api/src/core/modules.generated.ts');
  await writeFile(outPath, content, 'utf8');
  console.log('[gen] Wrote', path.relative(root, outPath), `(${names.length} modules)`);
}

async function genWebFeatures() {
  const featuresDir = path.join(root, 'apps/web/src/features');
  let names = [];
  try {
    const entries = await readdir(featuresDir, { withFileTypes: true });
    for (const e of entries) {
      if (!e.isDirectory()) continue;
      const manifest = path.join(featuresDir, e.name, 'manifest.ts');
      if (await exists(manifest)) names.push(e.name);
    }
  } catch {}
  names.sort();

  const imports = names.map((n, i) => `import feat${i} from '../features/${n}/manifest.js';`).join('\n');
  const exports = `export const features = [${names.map((_, i) => `feat${i}`).join(', ')}];\nexport default features;\n`;
  const content = `// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit\n${imports}\n${exports}`;
  const outPath = path.join(root, 'apps/web/src/core/features.generated.ts');
  await writeFile(outPath, content, 'utf8').catch(() => {});
  console.log('[gen] Wrote', path.relative(root, outPath), `(${names.length} features)`);
}

await genApiModules();
await genWebFeatures();
